import 'emoji_data.dart';

/// Единый пул эмодзи на всё приложение — реакция на сообщение и обычный
/// эмодзи, вставляемый в текст (см. FullEmojiPicker), по своей природе
/// одно и то же, поэтому и список один: те же самые emojiCategories,
/// просто развёрнутые в плоский список без разбивки по категориям (как и
/// делает сам FullEmojiPicker). Отдельного, более узкого списка "только
/// для реакций" больше нет — раньше он существовал просто как тестовый
/// набор из 50 штук для проверки механизма панели.
final List<String> reactionEmojis = emojiCategories.values
    .expand((category) => category)
    .toList(growable: false);
