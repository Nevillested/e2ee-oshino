import 'package:dio/dio.dart' as dio;

/// Реестр активных CancelToken'ов текущих СКАЧИВАНИЙ медиа/файлов с
/// сервера, по mediaId — зеркало UploadCancelRegistry (та же идея, для
/// противоположного направления). ТЗ пользователя: "нужно добавить кнопку
/// отмены скачивания... везде, где происходит скачивание файла". Без этого
/// "отмена" могла бы только убрать локальные следы задачи, а сам HTTP-запрос
/// молча донашивал бы себя в фоне до конца.
///
/// ВАЖНО: это НЕ связано с последовательностью ключей Double Ratchet —
/// ключ/nonce/mac для расшифровки конкретного файла приходят ОТКРЫТО внутри
/// уже расшифрованного сообщения (см. media_cipher.dart — случайный
/// одноразовый AES-ключ на файл, не часть цепочки сообщений) и никак не
/// связаны с сессией переписки. Отмена скачивания прерывает только сетевую
/// закачку зашифрованных БАЙТОВ файла — расшифровка потом либо не
/// происходит вовсе (сеть прервалась раньше), либо идёт по уже полностью
/// скачанным байтам как обычно; ratchet-цепочку это не трогает.
class DownloadCancelRegistry {
  DownloadCancelRegistry._();

  static final Map<String, dio.CancelToken> _tokens = {};

  static dio.CancelToken register(String mediaId) {
    final token = dio.CancelToken();
    _tokens[mediaId] = token;
    return token;
  }

  static void unregister(String mediaId) {
    _tokens.remove(mediaId);
  }

  /// Не найден — значит скачивание либо уже закончилось, либо ещё не
  /// стартовало по-настоящему (стоит в очереди _downloadQueueTail) — токен
  /// в этом случае уже создан и зарегистрирован (см. register — вызывается
  /// сразу при постановке в очередь, а не когда до задачи реально дойдёт
  /// черёд), так что отмена сработает и здесь: сама сетевая задача, когда
  /// до неё дойдёт очередь, увидит уже отменённый токен и не станет
  /// начинать запрос вовсе.
  static void cancel(String mediaId) {
    final token = _tokens[mediaId];
    if (token != null && !token.isCancelled) {
      token.cancel('cancelled by user');
    }
  }
}
