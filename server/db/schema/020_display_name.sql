-- Отображаемое имя — необязательное, задаётся самим пользователем в
-- профиле (см. account_profile.go). В отличие от login (уникален,
-- редактированию не подлежит, используется как идентификатор), это чисто
-- презентационное поле: если задано — показывается ВЕЗДЕ вместо login
-- (список чатов, шапка чата, профиль, пересылка и т.д.), иначе клиент
-- сам откатывается на login. Видимость не ограничивается (в отличие от
-- status/birthday/avatar) — это не приватные данные, а то, как
-- пользователь сам представляется собеседникам.
ALTER TABLE accounts
    ADD COLUMN display_name TEXT;
