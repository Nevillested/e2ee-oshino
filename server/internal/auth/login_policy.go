package auth

import (
	"errors"
	"regexp"
)

// loginRe — только латинские буквы и цифры, 3-32 символа. Раньше логин не
// проверялся вообще (кроме списка reservedLogins) — можно было
// зарегистрировать кириллический омоглиф вроде "аdmin" (первая буква —
// кириллическая "а"), который IsReservedLogin не ловит (сравнение
// точное, посимвольное, просто без учёта регистра), а собеседник в 1-в-1
// переписке отличить его от настоящего "admin" на глаз не сможет — ровно
// та атака, от которой reservedLogins должен защищать.
var loginRe = regexp.MustCompile(`^[A-Za-z0-9]{3,32}$`)

// ValidateLogin — единые требования к логину, проверяются при регистрации
// (см. register.go). Разрешены только латиница и цифры — это же исключает
// пробелы, эмодзи и однажды исключает саму возможность визуальной подмены
// через похожие символы из других алфавитов.
func ValidateLogin(login string) error {
	if !loginRe.MatchString(login) {
		return errors.New("логин должен быть от 3 до 32 символов, только латинские буквы и цифры")
	}
	return nil
}
